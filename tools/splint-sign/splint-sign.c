/*
 * splint-sign - offline key management and ruleset signing for QSplintNX.
 *
 *   splint-sign keygen   <prefix>            -> <prefix>.key (64B), <prefix>.pub (32B)
 *   splint-sign header   <pubfile>           -> C header (splint_pubkey.h) on stdout
 *   splint-sign sign     <keyfile> <rules>   -> <rules>.sig (64B detached)
 *   splint-sign verify   <pubfile> <rules>   -> checks <rules>.sig, exit 0/1
 *
 * splintd never runs this; it only verifies, with the public key compiled in.
 * Keep the .key (private seed+key) offline. The demo key under demo/keys is a
 * throwaway for reproducibility, not a key to protect anything real.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "splint/splint_sig.h"

#define RULES_MAX (1u << 20)

static int read_all(const char *path, unsigned char *buf, size_t cap, size_t *out_len)
{
    FILE *f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "open %s failed\n", path); return -1; }
    size_t n = fread(buf, 1, cap, f);
    unsigned char extra;
    size_t more = fread(&extra, 1, 1, f);   /* one past cap: is the file too big? */
    fclose(f);
    if (more != 0) { fprintf(stderr, "%s larger than %zu bytes\n", path, cap); return -1; }
    *out_len = n;
    return 0;
}

static int write_all(const char *path, const unsigned char *buf, size_t len)
{
    FILE *f = fopen(path, "wb");
    if (!f) { fprintf(stderr, "create %s failed\n", path); return -1; }
    size_t n = fwrite(buf, 1, len, f);
    fclose(f);
    if (n != len) { fprintf(stderr, "short write %s\n", path); return -1; }
    return 0;
}

static int cmd_keygen(const char *prefix)
{
    unsigned char seed[SPLINT_SEED_BYTES];
    FILE *rng = fopen("/dev/urandom", "rb");
    if (!rng || fread(seed, 1, sizeof seed, rng) != sizeof seed) {
        fprintf(stderr, "cannot read /dev/urandom\n");
        if (rng) fclose(rng);
        return 1;
    }
    fclose(rng);

    unsigned char pub[SPLINT_PUBKEY_BYTES], sk[SPLINT_SECKEY_BYTES];
    if (splint_sig_keypair_from_seed(pub, sk, seed) != 0) {
        fprintf(stderr, "keypair derivation failed\n");
        return 1;
    }

    char path[512];
    snprintf(path, sizeof path, "%s.key", prefix);
    if (write_all(path, sk, sizeof sk) != 0) return 1;
    snprintf(path, sizeof path, "%s.pub", prefix);
    if (write_all(path, pub, sizeof pub) != 0) return 1;
    fprintf(stderr, "wrote %s.key (keep offline) and %s.pub\n", prefix, prefix);
    return 0;
}

static int cmd_header(const char *pubfile)
{
    unsigned char pub[SPLINT_PUBKEY_BYTES];
    size_t n = 0;
    if (read_all(pubfile, pub, sizeof pub, &n) != 0) return 1;
    if (n != SPLINT_PUBKEY_BYTES) { fprintf(stderr, "pubkey must be 32 bytes\n"); return 1; }

    printf("/* Generated by splint-sign header. The trusted ruleset-signing\n");
    printf(" * public key, compiled into splintd. SPDX-License-Identifier: Apache-2.0 */\n");
    printf("#ifndef SPLINT_PUBKEY_H\n#define SPLINT_PUBKEY_H\n\n");
    printf("static const unsigned char SPLINT_TRUSTED_PUBKEY[32] = {\n    ");
    for (unsigned i = 0; i < SPLINT_PUBKEY_BYTES; i++)
        printf("0x%02x%s", pub[i], i == SPLINT_PUBKEY_BYTES - 1 ? "\n" :
               (i % 8 == 7 ? ",\n    " : ", "));
    printf("};\n\n#endif /* SPLINT_PUBKEY_H */\n");
    return 0;
}

static int cmd_sign(const char *keyfile, const char *rules)
{
    unsigned char sk[SPLINT_SECKEY_BYTES];
    size_t n = 0;
    if (read_all(keyfile, sk, sizeof sk, &n) != 0) return 1;
    if (n != SPLINT_SECKEY_BYTES) { fprintf(stderr, "key must be 64 bytes\n"); return 1; }

    unsigned char *buf = malloc(RULES_MAX);
    if (!buf) return 1;
    size_t len = 0;
    if (read_all(rules, buf, RULES_MAX, &len) != 0) { free(buf); return 1; }

    unsigned char sig[SPLINT_SIG_BYTES];
    int r = splint_sig_sign(sig, buf, len, sk);
    free(buf);
    if (r != 0) { fprintf(stderr, "signing failed\n"); return 1; }

    char sigpath[512];
    snprintf(sigpath, sizeof sigpath, "%s.sig", rules);
    if (write_all(sigpath, sig, sizeof sig) != 0) return 1;
    fprintf(stderr, "wrote %s\n", sigpath);
    return 0;
}

static int cmd_verify(const char *pubfile, const char *rules)
{
    unsigned char pub[SPLINT_PUBKEY_BYTES];
    size_t n = 0;
    if (read_all(pubfile, pub, sizeof pub, &n) != 0 || n != SPLINT_PUBKEY_BYTES) {
        fprintf(stderr, "bad pubkey\n"); return 2;
    }
    unsigned char *buf = malloc(RULES_MAX);
    if (!buf) return 2;
    size_t len = 0;
    if (read_all(rules, buf, RULES_MAX, &len) != 0) { free(buf); return 2; }

    char sigpath[512];
    snprintf(sigpath, sizeof sigpath, "%s.sig", rules);
    unsigned char sig[SPLINT_SIG_BYTES];
    size_t sn = 0;
    if (read_all(sigpath, sig, sizeof sig, &sn) != 0 || sn != SPLINT_SIG_BYTES) {
        fprintf(stderr, "bad or missing %s\n", sigpath); free(buf); return 1;
    }
    int ok = splint_sig_verify(buf, len, sig, pub) == 0;
    free(buf);
    printf("%s: %s\n", rules, ok ? "OK (signature valid)" : "FAIL (signature invalid)");
    return ok ? 0 : 1;
}

int main(int argc, char **argv)
{
    if (argc >= 3 && strcmp(argv[1], "keygen") == 0)
        return cmd_keygen(argv[2]);
    if (argc >= 3 && strcmp(argv[1], "header") == 0)
        return cmd_header(argv[2]);
    if (argc >= 4 && strcmp(argv[1], "sign") == 0)
        return cmd_sign(argv[2], argv[3]);
    if (argc >= 4 && strcmp(argv[1], "verify") == 0)
        return cmd_verify(argv[2], argv[3]);

    fprintf(stderr,
        "usage:\n"
        "  splint-sign keygen <prefix>\n"
        "  splint-sign header <pubfile>\n"
        "  splint-sign sign   <keyfile> <rulesfile>\n"
        "  splint-sign verify <pubfile> <rulesfile>\n");
    return 2;
}
